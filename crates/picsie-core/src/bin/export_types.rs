//! TypeScript's contract is generated from Rust. No parallel schema to maintain.
use picsie_core::{
    canvas_size::CanvasSizeOptions,
    crop::{CropRatio, CropRect},
    editor::*,
    geometry::Viewport,
    history::{HistoryInfo, Selection},
    model::*,
};
use serde::Serialize;
use ts_rs::TS;
#[derive(TS, Serialize)]
#[serde(rename_all = "camelCase")]
struct EditorState {
    document: Document,
    history: HistoryInfo,
    selection: Selection,
    paint_target: PaintTarget,
    mask_mode: MaskMode,
    tool: Tool,
    color: String,
    brush_size: f64,
    brush_opacity: f64,
    viewport: Viewport,
    crop_rect: Option<CropRect>,
    crop_ratio: CropRatio,
    layer_rows: Vec<LayerRow>,
    pixel_selection_bounds: Option<picsie_core::pixel_selection::SelectionBounds>,
    pixel_selection_feather: Option<f64>,
    marquee_kind: picsie_core::pixel_selection::MarqueeKind,
    selection_mode: picsie_core::pixel_selection::PixelSelectionMode,
    text_edit_requests: u64,
}
fn main() {
    let mut out =
        String::from("// Generated by cargo run -p picsie-core --bin export_types. Do not edit.\n");
    macro_rules! export{($($t:ty),*)=>{$(out.push_str("export ");out.push_str(&<$t>::decl(&ts_rs::Config::default()));out.push('\n');)*};}
    export!(
        Point,
        Shape,
        FontFamily,
        Blend,
        Sampling,
        Content,
        MaskMode,
        LayerMask,
        MaskPlacement,
        Layer,
        Document,
        Viewport,
        Selection,
        HistoryInfo,
        Tool,
        PaintTarget,
        SelectionMode,
        Phase,
        Modifiers,
        PointerSample,
        InitialDocument,
        Side,
        CanvasSizeOptions,
        CropRect,
        CropRatio,
        LayerRow,
        picsie_core::pixel_selection::SelectionBounds,
        picsie_core::pixel_selection::MarqueeKind,
        picsie_core::pixel_selection::PixelSelectionMode,
        Command,
        EditorState
    );
    std::fs::create_dir_all("src/engine").unwrap();
    std::fs::write("src/engine/types.ts", out).unwrap();
}
