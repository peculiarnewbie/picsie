//! TypeScript's contract is generated from Rust. No parallel schema to maintain.
use picsie_core::{
    canvas_size::CanvasSizeOptions,
    editor::*,
    geometry::Viewport,
    history::{HistoryInfo, Selection},
    model::*,
};
use serde::Serialize;
use ts_rs::TS;
#[derive(TS, Serialize)]
#[serde(rename_all = "camelCase")]
struct EditorState {
    document: Document,
    history: HistoryInfo,
    selection: Selection,
    paint_target: PaintTarget,
    mask_mode: MaskMode,
    tool: Tool,
    color: String,
    brush_size: f64,
    brush_opacity: f64,
    viewport: Viewport,
}
fn main() {
    let mut out =
        String::from("// Generated by cargo run -p picsie-core --bin export_types. Do not edit.\n");
    macro_rules! export{($($t:ty),*)=>{$(out.push_str("export ");out.push_str(&<$t>::decl(&ts_rs::Config::default()));out.push('\n');)*};}
    export!(
        Point,
        Shape,
        FontFamily,
        Blend,
        Content,
        MaskMode,
        LayerMask,
        Layer,
        Document,
        Viewport,
        Selection,
        HistoryInfo,
        Tool,
        PaintTarget,
        SelectionMode,
        Phase,
        Modifiers,
        PointerSample,
        InitialDocument,
        Side,
        CanvasSizeOptions,
        Command,
        EditorState
    );
    std::fs::create_dir_all("src/engine").unwrap();
    std::fs::write("src/engine/types.ts", out).unwrap();
}
