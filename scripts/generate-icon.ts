import { createCanvas } from "@napi-rs/canvas";
import { mkdir, writeFile } from "node:fs/promises";

const canvas = createCanvas(512, 512);
const ctx = canvas.getContext("2d");
ctx.fillStyle = "#191d34";
ctx.beginPath();
ctx.roundRect(24, 24, 464, 464, 108);
ctx.fill();
const gradient = ctx.createLinearGradient(120, 90, 400, 410);
gradient.addColorStop(0, "#f7a8dc");
gradient.addColorStop(0.5, "#b99dff");
gradient.addColorStop(1, "#70d4ed");
ctx.strokeStyle = gradient;
ctx.lineWidth = 68;
ctx.lineCap = "round";
ctx.lineJoin = "round";
ctx.beginPath();
ctx.moveTo(143, 398);
ctx.lineTo(143, 113);
ctx.lineTo(268, 113);
ctx.bezierCurveTo(344, 113, 391, 149, 391, 213);
ctx.bezierCurveTo(391, 278, 344, 315, 268, 315);
ctx.lineTo(143, 315);
ctx.stroke();
ctx.fillStyle = "#fff3dd";
ctx.beginPath();
ctx.arc(274, 207, 28, 0, Math.PI * 2);
ctx.fill();
await mkdir("resources", { recursive: true });
await writeFile("resources/icon.png", await canvas.encode("png"));
